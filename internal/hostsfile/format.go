// Package hostsfile reads and writes the one hosts file dnsmasq-manager owns
// in the dnsmasq hosts directory.
//
// The file is a dnsmasq hosts file whose comment lines carry the state
// dnsmasq does not need: each name's source and the external-dns TXT
// ownership records. Rendering is canonical, so a state has exactly one
// rendering, and Parse accepts only that rendering. That is how a hand edit
// or a truncated file is caught.
package hostsfile

import (
	"bytes"
	"encoding/json"
	"fmt"
	"net/netip"
	"strconv"
	"strings"

	"github.com/gsdevme/dnsmasq-manager/internal/records"
)

// FileName is the name of the managed file inside the hosts directory.
const FileName = "dnsmasq-manager.hosts"

const (
	headerLine = "# Generated by dnsmasq-manager. Do not edit: a file changed by hand is refused at start-up."
	formatLine = "#@ format 1"
	namePrefix = "#@ name "
	txtPrefix  = "#@ txt "
)

// txtLine is the JSON object on a "#@ txt" line. Its field order is the key
// order in the file.
type txtLine struct {
	DNSName     string   `json:"dnsName"`
	Targets     []string `json:"targets"`
	OwnedRecord string   `json:"ownedRecord,omitempty"`
}

// Render returns the managed file for s. s must be canonical, as
// records.State documents; Draft.State always returns one. An empty state
// renders as the two header lines.
func Render(s records.State) []byte {
	var b bytes.Buffer
	b.WriteString(headerLine + "\n" + formatLine + "\n")
	for i, r := range s.Records {
		if i == 0 || s.Records[i-1].Name != r.Name {
			b.WriteString(namePrefix + r.Name + " " + string(r.Source) + "\n")
		}
		for _, v := range r.Values {
			b.WriteString(v.String() + " " + r.Name + "\n")
		}
	}
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	for _, t := range s.TXTs {
		b.WriteString(txtPrefix)
		if err := enc.Encode(txtLine{DNSName: t.Name, Targets: t.Targets, OwnedRecord: t.OwnedRecord}); err != nil {
			panic(fmt.Sprintf("hostsfile: encoding a TXT line: %v", err))
		}
	}
	return b.Bytes()
}

// ParseError is a refusal of the managed file. Line is the 1-based line at
// fault, or 0 when the fault is in the file as a whole, such as a file that
// parses but is not in canonical form.
type ParseError struct {
	Line   int
	Reason string
}

// Error returns "<line>: <reason>", so a caller that prefixes the path and a
// colon gets the conventional "path:line: reason".
func (e *ParseError) Error() string {
	return strconv.Itoa(e.Line) + ": " + e.Reason
}

// Parse reads a managed file strictly. Every record and TXT is validated
// against policy, and the file must equal the rendering of the state it
// holds byte for byte. A file with whole entries removed is still canonical,
// so it parses. Every error is a *ParseError; a validation failure is reported
// at the first line of the entry.
func Parse(data []byte, policy records.Policy) (records.State, error) {
	p := parser{policy: policy}
	if err := p.parse(string(data)); err != nil {
		return records.State{}, err
	}
	if !bytes.Equal(Render(p.state), data) {
		return records.State{}, &ParseError{Line: 0, Reason: "not in canonical form"}
	}
	return p.state, nil
}

// parser builds a State from the managed file one line at a time.
type parser struct {
	policy records.Policy
	state  records.State

	block     *block
	lastName  string
	seenTXT   bool
	lastTXT   string
	lastValue netip.Addr
}

// block is the "#@ name" entry being read: its name, source, first line and
// the addresses read so far.
type block struct {
	name   string
	source records.Source
	line   int
	a      []netip.Addr
	aaaa   []netip.Addr
}

// parse splits data into lines and parses each, then closes the last block.
func (p *parser) parse(data string) error {
	if data == "" {
		return &ParseError{Line: 1, Reason: "missing header"}
	}
	lines := strings.Split(data, "\n")
	if last := lines[len(lines)-1]; last != "" {
		return &ParseError{Line: len(lines), Reason: "no final newline"}
	}
	lines = lines[:len(lines)-1]
	if lines[0] != headerLine {
		return &ParseError{Line: 1, Reason: "missing header"}
	}
	if len(lines) < 2 {
		return &ParseError{Line: 2, Reason: "missing format line"}
	}
	if lines[1] != formatLine {
		if strings.HasPrefix(lines[1], "#@ format ") {
			return &ParseError{Line: 2, Reason: fmt.Sprintf("unsupported format %q", strings.TrimPrefix(lines[1], "#@ format "))}
		}
		return &ParseError{Line: 2, Reason: "missing format line"}
	}
	for i, line := range lines[2:] {
		if err := p.line(i+3, line); err != nil {
			return err
		}
	}
	return p.closeBlock()
}

// line parses one line after the header. n is its 1-based line number.
func (p *parser) line(n int, line string) error {
	if reason := whitespaceFault(line); reason != "" {
		return &ParseError{Line: n, Reason: reason}
	}
	switch {
	case strings.HasPrefix(line, namePrefix):
		return p.nameLine(n, strings.TrimPrefix(line, namePrefix))
	case strings.HasPrefix(line, txtPrefix):
		return p.txtLine(n, strings.TrimPrefix(line, txtPrefix))
	case strings.HasPrefix(line, "#@"):
		return &ParseError{Line: n, Reason: fmt.Sprintf("unknown directive %q", line)}
	case strings.HasPrefix(line, "#"):
		return &ParseError{Line: n, Reason: "comment lines are not allowed"}
	default:
		return p.addressLine(n, line)
	}
}

// whitespaceFault describes the stray whitespace in line, or returns "" when
// it has none: the file allows only single spaces between fields.
//
// A "#@ txt" line is exempt from the single-space rule, because its JSON
// strings hold TXT targets and owned records byte for byte and those may
// contain runs of spaces. JSON escapes tabs and line endings inside strings
// and the object ends in '}', so the other rules still hold for it, and the
// re-render comparison in Parse enforces the rest of its canonical form.
func whitespaceFault(line string) string {
	txt := strings.HasPrefix(line, txtPrefix)
	switch {
	case line == "":
		return "blank line"
	case strings.Contains(line, "\r"):
		return "carriage return; the file uses LF line endings"
	case strings.Contains(line, "\t"):
		return "tab character"
	case strings.HasSuffix(line, " "):
		return "trailing space"
	case strings.HasPrefix(line, " "):
		return "leading space"
	case !txt && strings.Contains(line, "  "):
		return "more than one space between fields"
	}
	return ""
}

// nameLine starts a new block from the rest of a "#@ name" line.
func (p *parser) nameLine(n int, rest string) error {
	if p.seenTXT {
		return &ParseError{Line: n, Reason: "name block after TXT lines"}
	}
	if err := p.closeBlock(); err != nil {
		return err
	}
	fields := strings.Split(rest, " ")
	if len(fields) != 2 {
		return &ParseError{Line: n, Reason: "name line must be \"#@ name <name> <source>\""}
	}
	name, source := fields[0], records.Source(fields[1])
	if source != records.SourceAPI && source != records.SourceExternalDNS {
		return &ParseError{Line: n, Reason: fmt.Sprintf("unknown source %q", source)}
	}
	if p.lastName != "" && name <= p.lastName {
		if name == p.lastName {
			return &ParseError{Line: n, Reason: fmt.Sprintf("duplicate name %s", name)}
		}
		return &ParseError{Line: n, Reason: fmt.Sprintf("name %s is out of order after %s", name, p.lastName)}
	}
	p.lastName = name
	p.block = &block{name: name, source: source, line: n}
	p.lastValue = netip.Addr{}
	return nil
}

// addressLine adds the address on a "<address> <name>" line to the open
// block.
func (p *parser) addressLine(n int, line string) error {
	if p.seenTXT {
		return &ParseError{Line: n, Reason: "address line after TXT lines"}
	}
	if p.block == nil {
		return &ParseError{Line: n, Reason: "address line before any \"#@ name\" line"}
	}
	fields := strings.Split(line, " ")
	if len(fields) != 2 {
		return &ParseError{Line: n, Reason: "address line must be \"<address> <name>\""}
	}
	text, name := fields[0], fields[1]
	if name != p.block.name {
		return &ParseError{Line: n, Reason: fmt.Sprintf("name %s does not match its block %s", name, p.block.name)}
	}
	addr, err := netip.ParseAddr(text)
	if err != nil {
		return &ParseError{Line: n, Reason: fmt.Sprintf("%q is not an IP address", text)}
	}
	if addr.String() != text {
		return &ParseError{Line: n, Reason: fmt.Sprintf("%q is not in canonical form", text)}
	}
	if p.lastValue.IsValid() && p.lastValue.Compare(addr) >= 0 {
		if p.lastValue.Is6() && addr.Is4() {
			return &ParseError{Line: n, Reason: "IPv4 address after an IPv6 address"}
		}
		return &ParseError{Line: n, Reason: "addresses are not sorted and unique"}
	}
	p.lastValue = addr
	if addr.Is4() {
		p.block.a = append(p.block.a, addr)
	} else {
		p.block.aaaa = append(p.block.aaaa, addr)
	}
	return nil
}

// txtLine adds the TXT ownership record encoded in the rest of a "#@ txt"
// line.
func (p *parser) txtLine(n int, rest string) error {
	if err := p.closeBlock(); err != nil {
		return err
	}
	p.seenTXT = true
	var l txtLine
	if err := json.Unmarshal([]byte(rest), &l); err != nil {
		return &ParseError{Line: n, Reason: fmt.Sprintf("TXT line is not a JSON object: %v", err)}
	}
	t := records.TXT{Name: l.DNSName, Targets: l.Targets, OwnedRecord: l.OwnedRecord}
	if p.lastTXT != "" && t.Name <= p.lastTXT {
		if t.Name == p.lastTXT {
			return &ParseError{Line: n, Reason: fmt.Sprintf("duplicate TXT %s", t.Name)}
		}
		return &ParseError{Line: n, Reason: fmt.Sprintf("TXT %s is out of order after %s", t.Name, p.lastTXT)}
	}
	if err := p.policy.CheckTXT(t); err != nil {
		return &ParseError{Line: n, Reason: err.Error()}
	}
	p.lastTXT = t.Name
	p.state.TXTs = append(p.state.TXTs, t)
	return nil
}

// closeBlock validates the open block, if any, and adds its records to the
// state.
func (p *parser) closeBlock() error {
	b := p.block
	if b == nil {
		return nil
	}
	p.block = nil
	if len(b.a) == 0 && len(b.aaaa) == 0 {
		return &ParseError{Line: b.line, Reason: fmt.Sprintf("name %s has no address lines", b.name)}
	}
	for _, r := range []records.Record{
		{Name: b.name, Type: records.TypeA, Values: b.a, Source: b.source},
		{Name: b.name, Type: records.TypeAAAA, Values: b.aaaa, Source: b.source},
	} {
		if len(r.Values) == 0 {
			continue
		}
		if err := p.policy.CheckRecord(r); err != nil {
			return &ParseError{Line: b.line, Reason: err.Error()}
		}
		p.state.Records = append(p.state.Records, r)
	}
	return nil
}
