func TestParseAcceptsEntryRemoved(t *testing.T) {
	example := readExample(t)
	tests := []struct {
		name   string
		remove string
		want   func(records.State) records.State
	}{
		{
			name:   "name block",
			remove: "#@ name nas.home.example.test api\n10.0.0.40 nas.home.example.test\n",
			want: func(s records.State) records.State {
				s.Records = s.Records[:2]
				return s
			},
		},
		{
			name:   "TXT line",
			remove: `#@ txt {"dnsName":"a-app.home.example.test","targets":["\"heritage=external-dns,external-dns/owner=default,external-dns/resource=ingress/default/app\""],"ownedRecord":"app.home.example.test"}` + "\n",
			want: func(s records.State) records.State {
				s.TXTs = nil
				return s
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			data := strings.Replace(example, tt.remove, "", 1)
			if data == example {
				t.Fatal("nothing removed")
			}
			got, err := hostsfile.Parse([]byte(data), policy())
			if err != nil {
				t.Fatalf("Parse: %v", err)
			}
			if want := tt.want(exampleState()); !got.Equal(want) {
				t.Errorf("Parse = %+v, want %+v", got, want)
			}
		})
	}
}

