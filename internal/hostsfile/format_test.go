const header = "# Generated by dnsmasq-manager. Do not edit: a file changed by hand is refused at start-up.\n#@ format 1\n"

// policy allows the zone and prefixes every test record uses.
func policy() records.Policy {
	return records.Policy{
		Zones:    []string{"home.example.test"},
		Prefixes: []netip.Prefix{netip.MustParsePrefix("10.0.0.0/24"), netip.MustParsePrefix("fd00:10::/64")},
	}
}

// addrs parses each of s as an address.
func addrs(s ...string) []netip.Addr {
	out := make([]netip.Addr, len(s))
	for i, v := range s {
		out[i] = netip.MustParseAddr(v)
	}
	return out
}

// exampleState is the state behind testdata/example.hosts.
func exampleState() records.State {
	return records.State{
		Records: []records.Record{
			{Name: "app.home.example.test", Type: records.TypeA, Values: addrs("10.0.0.80"), Source: records.SourceExternalDNS},
			{Name: "app.home.example.test", Type: records.TypeAAAA, Values: addrs("fd00:10::80"), Source: records.SourceExternalDNS},
			{Name: "nas.home.example.test", Type: records.TypeA, Values: addrs("10.0.0.40"), Source: records.SourceAPI},
		},
		TXTs: []records.TXT{{
			Name:        "a-app.home.example.test",
			Targets:     []string{`"heritage=external-dns,external-dns/owner=default,external-dns/resource=ingress/default/app"`},
			OwnedRecord: "app.home.example.test",
		}},
	}
}

// readExample returns the bytes of testdata/example.hosts.
func readExample(t *testing.T) string {
	t.Helper()
	data, err := os.ReadFile("testdata/example.hosts")
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func TestRenderExample(t *testing.T) {
	want := readExample(t)
	if got := string(hostsfile.Render(exampleState())); got != want {
		t.Errorf("Render =\n%s\nwant\n%s", got, want)
	}
}

func TestRenderEmpty(t *testing.T) {
	if got := string(hostsfile.Render(records.State{})); got != header {
		t.Errorf("Render = %q, want %q", got, header)
	}
}

func TestRoundTrip(t *testing.T) {
	tests := []struct {
		name  string
		state records.State
	}{
		{name: "empty", state: records.State{}},
		{name: "A only", state: records.State{Records: []records.Record{
			{Name: "nas.home.example.test", Type: records.TypeA, Values: addrs("10.0.0.40", "10.0.0.41"), Source: records.SourceAPI},
		}}},
		{name: "A and AAAA", state: records.State{Records: []records.Record{
			{Name: "app.home.example.test", Type: records.TypeA, Values: addrs("10.0.0.80"), Source: records.SourceExternalDNS},
			{Name: "app.home.example.test", Type: records.TypeAAAA, Values: addrs("fd00:10::80", "fd00:10::81"), Source: records.SourceExternalDNS},
			{Name: "web.home.example.test", Type: records.TypeAAAA, Values: addrs("fd00:10::90"), Source: records.SourceAPI},
		}}},
		{name: "TXT with awkward targets", state: records.State{TXTs: []records.TXT{
			{Name: "a-app.home.example.test", Targets: []string{`"quoted" <tag> & more`, "café ☕"}},
			{Name: "app.home.example.test", Targets: []string{"x"}, OwnedRecord: "app.home.example.test"},
		}}},
		{name: "TXT with whitespace in strings", state: records.State{TXTs: []records.TXT{
			{Name: "a-app.home.example.test", Targets: []string{"two  spaces", "trailing ", "   ", "tab\there"}},
			{Name: "b-app.home.example.test", Targets: []string{" leading", "cr\rlf\n", "nul\x00"}, OwnedRecord: "app  home\t"},
		}}},
		{name: "example", state: exampleState()},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := hostsfile.Parse(hostsfile.Render(tt.state), policy())
			if err != nil {
				t.Fatalf("Parse: %v", err)
			}
			if !got.Equal(tt.state) {
				t.Errorf("Parse(Render(s)) = %+v, want %+v", got, tt.state)
			}
		})
	}
}

func TestParseRefuses(t *testing.T) {
	const (
		nameA = "#@ name app.home.example.test api\n"
		addrA = "10.0.0.80 app.home.example.test\n"
		nameB = "#@ name nas.home.example.test api\n"
		addrB = "10.0.0.40 nas.home.example.test\n"
		txt   = `#@ txt {"dnsName":"a-app.home.example.test","targets":["x"]}` + "\n"
	)
	tests := []struct {
		name     string
		data     string
		wantLine int
	}{
		{name: "empty file", data: "", wantLine: 1},
		{name: "missing header", data: "#@ format 1\n", wantLine: 1},
		{name: "missing format line", data: header[:strings.Index(header, "\n")+1], wantLine: 2},
		{name: "format 2", data: strings.Replace(header, "format 1", "format 2", 1), wantLine: 2},
		{name: "address before any name", data: header + addrA, wantLine: 3},
		{name: "address of another name", data: header + nameA + addrA + addrB, wantLine: 5},
		{name: "name block without addresses", data: header + nameA + nameB + addrB, wantLine: 3},
		{name: "name block without addresses at end", data: header + nameA, wantLine: 3},
		{name: "unknown source", data: header + "#@ name app.home.example.test other\n" + addrA, wantLine: 3},
		{name: "name line with extra field", data: header + "#@ name app.home.example.test api x\n" + addrA, wantLine: 3},
		{name: "names out of order", data: header + nameB + addrB + nameA + addrA, wantLine: 5},
		{name: "duplicate name", data: header + nameA + addrA + nameA + addrA, wantLine: 5},
		{name: "IPv6 before IPv4", data: header + nameA + "fd00:10::80 app.home.example.test\n" + addrA, wantLine: 5},
		{name: "unsorted addresses", data: header + nameA + "10.0.0.81 app.home.example.test\n" + addrA, wantLine: 5},
		{name: "duplicate address", data: header + nameA + addrA + addrA, wantLine: 5},
		{name: "leading zero", data: header + nameA + "10.0.0.080 app.home.example.test\n", wantLine: 4},
		{name: "non-canonical IPv6", data: header + nameA + "fd00:10:0:0::80 app.home.example.test\n", wantLine: 4},
		{name: "IPv4-mapped IPv6", data: header + nameA + "::ffff:10.0.0.80 app.home.example.test\n", wantLine: 3},
		{name: "zone suffix", data: header + nameA + "fe80::1%eth0 app.home.example.test\n", wantLine: 3},
		{name: "two spaces", data: header + nameA + "10.0.0.80  app.home.example.test\n", wantLine: 4},
		{name: "tab", data: header + nameA + "10.0.0.80\tapp.home.example.test\n", wantLine: 4},
		{name: "trailing space", data: header + nameA + "10.0.0.80 app.home.example.test \n", wantLine: 4},
		{name: "blank line", data: header + nameA + addrA + "\n" + nameB + addrB, wantLine: 5},
		{name: "CRLF", data: header + nameA + "10.0.0.80 app.home.example.test\r\n", wantLine: 4},
		{name: "no final newline", data: header + nameA + strings.TrimSuffix(addrA, "\n"), wantLine: 4},
		{name: "plain comment", data: header + "# hello\n" + nameA + addrA, wantLine: 3},
		{name: "unknown directive", data: header + "#@ alias app\n" + nameA + addrA, wantLine: 3},
		{name: "second format line", data: header + "#@ format 1\n", wantLine: 3},
		{name: "name after TXT", data: header + txt + nameA + addrA, wantLine: 4},
		{name: "address after TXT", data: header + nameA + addrA + txt + addrA, wantLine: 6},
		{name: "TXT with carriage return", data: header + strings.TrimSuffix(txt, "\n") + "\r\n", wantLine: 3},
		{name: "TXT with raw tab", data: header + `#@ txt {"dnsName":"a-app.home.example.test",` + "\t" + `"targets":["x"]}` + "\n", wantLine: 3},
		{name: "TXT trailing space", data: header + strings.TrimSuffix(txt, "\n") + " \n", wantLine: 3},
		{name: "TXT two spaces between tokens", data: header + `#@ txt {"dnsName":"a-app.home.example.test",  "targets":["x"]}` + "\n", wantLine: 0},
		{name: "TXT not JSON", data: header + "#@ txt {nope\n", wantLine: 3},
		{name: "TXTs out of order", data: header + `#@ txt {"dnsName":"b.home.example.test","targets":["x"]}` + "\n" + txt, wantLine: 4},
		{name: "duplicate TXT", data: header + txt + txt, wantLine: 4},
		{name: "TXT outside zone", data: header + `#@ txt {"dnsName":"a.other.test","targets":["x"]}` + "\n", wantLine: 3},
		{name: "TXT without targets", data: header + `#@ txt {"dnsName":"a.home.example.test","targets":[]}` + "\n", wantLine: 3},
		{name: "TXT keys reordered", data: header + `#@ txt {"targets":["x"],"dnsName":"a-app.home.example.test"}` + "\n", wantLine: 0},
		{name: "TXT extra whitespace", data: header + `#@ txt {"dnsName": "a-app.home.example.test","targets":["x"]}` + "\n", wantLine: 0},
		{name: "TXT empty ownedRecord", data: header + `#@ txt {"dnsName":"a-app.home.example.test","targets":["x"],"ownedRecord":""}` + "\n", wantLine: 0},
		{name: "record outside zone", data: header + "#@ name app.other.test api\n10.0.0.80 app.other.test\n", wantLine: 3},
		{name: "uppercase name", data: header + "#@ name App.home.example.test api\n10.0.0.80 App.home.example.test\n", wantLine: 3},
		{name: "value outside prefixes", data: header + nameA + "10.0.1.80 app.home.example.test\n", wantLine: 3},
		{name: "IPv6 outside prefixes", data: header + nameA + addrA + "fd00:11::80 app.home.example.test\n", wantLine: 3},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := hostsfile.Parse([]byte(tt.data), policy())
			var perr *hostsfile.ParseError
			if !errors.As(err, &perr) {
				t.Fatalf("err = %v, want a *ParseError", err)
			}
			if perr.Line != tt.wantLine {
				t.Errorf("Line = %d, want %d (reason %q)", perr.Line, tt.wantLine, perr.Reason)
			}
			if perr.Reason == "" {
				t.Error("Reason is empty")
			}
		})
	}
}

// TestParseTXTWhitespaceRegression pins that whitespace inside a TXT's JSON
// strings, which CheckTXT allows, does not make the saved file unreadable.
func TestParseTXTWhitespaceRegression(t *testing.T) {
	s := records.State{TXTs: []records.TXT{{
		Name:        "a-app.home.example.test",
		Targets:     []string{`"heritage=external-dns,external-dns/owner=two  spaces"`},
		OwnedRecord: "app.home.example.test",
	}}}
	if err := policy().Check(s); err != nil {
		t.Fatalf("Check: %v", err)
	}
	data := hostsfile.Render(s)
	if !strings.Contains(string(data), "two  spaces") {
		t.Fatalf("Render = %q, want the double space kept", data)
	}
	got, err := hostsfile.Parse(data, policy())
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	if !got.Equal(s) {
		t.Errorf("Parse(Render(s)) = %+v, want %+v", got, s)
	}
}

